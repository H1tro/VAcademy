export function checkAnswer(value: string, expected: string): boolean {
  const normalize = (text: string) => text.trim().toLowerCase().replace(/,/g, '.').replace(/\s+/g, ' ');
  const a = normalize(value), b = normalize(expected);
  if (!a) return false;
  const number = /^[+-]?(?:\d+(?:\.\d*)?|\.\d+)$/;
  if (number.test(a) && number.test(b)) return Math.abs(Number(a) - Number(b)) <= 1e-9;
  return a === b;
}
